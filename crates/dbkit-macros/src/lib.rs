//! Derive macros for `dbkit`.
//!
//! Currently the derive only parses and validates the `#[db(...)]`
//! annotations; generating the model, patch and insert code is a later step.

use proc_macro::TokenStream;

mod annotations;

/// Reads the `#[db(...)]` annotations of a model struct.
///
/// Accepted on the struct: `#[db(table = "...")]`.
/// Accepted on a field: `#[db(primary_key)]`, `#[db(version)]`,
/// `#[db(created_at)]`, `#[db(updated_at)]`.
///
/// Only `table` and `primary_key` are required; a table without a version or
/// audit column omits those annotations.
///
/// The derive emits nothing yet, so code generated by hand stays authoritative
/// while the annotation vocabulary settles.
#[proc_macro_derive(DbModel, attributes(db))]
pub fn derive_db_model(input: TokenStream) -> TokenStream {
    let input = syn::parse_macro_input!(input as syn::DeriveInput);

    match annotations::parse(&input) {
        Ok(_) => TokenStream::new(),
        Err(error) => error.to_compile_error().into(),
    }
}
