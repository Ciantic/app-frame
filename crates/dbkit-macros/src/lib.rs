//! Derive macros for `dbkit`.
//!
//! `DbModel` parses the `#[db(...)]` annotations and emits
//! `impl dbkit::Model`, whose `META` const describes the table at runtime.
//! `DbPatch` reads the same annotations and emits the model's patch input
//! type, and the same expansion emits the model's selectable column enum.
//! `DbType` records the database type of a value type, so a model field of
//! that type needs no `pgtype` or `pgdefault` of its own. `DbValue` gives a
//! newtype the borrow conversion a column handle takes.

use proc_macro::TokenStream;
use proc_macro2::TokenStream as TokenStream2;
use quote::format_ident;
use quote::quote;
use syn::DeriveInput;
use syn::Expr;

mod annotations;
mod derive_columns;
mod derive_patch;
mod derive_select;
mod derive_value;

/// Reads the `#[db(...)]` annotations of a model struct and generates
/// `impl dbkit::Model for ...`, carrying them as `Model::meta()`.
///
/// Accepted on the struct: `#[db(table = "...")]` for a table row,
/// `#[db(subquery = "...")]` for rows a query produces, or `#[db(fragment)]`
/// for a group of columns that another model embeds. The three generate
/// different `Model::meta()` values, `Meta::Table`, `Meta::SubQuery` and
/// `Meta::Fragment`, so a fragment never carries a table name or key and a
/// subquery carries its SQL instead of a table.
/// Accepted on a field: `#[db(pgtype = "...")]`, `#[db(pgdefault = "...")]`,
/// `#[db(primary_key)]`, `#[db(version)]`, `#[db(created_at)]`,
/// `#[db(updated_at)]`, `#[db(query_ops(eq, neq, ...))]`, and
/// `#[db(flatten)]`, which splices the field type's `meta().columns` into the
/// table's columns.
///
/// The same expansion also emits the model's selectable column enum,
/// `<Model>Column`, whose variants carry the column metadata; the model's
/// `TableMeta` holds those same values erased as `dbkit::ErasedColumn`, so the
/// two cannot disagree. A `#[db(flatten)]` field contributes a variant that
/// wraps the fragment's own enum, so a flattened column stays selectable as
/// `<Model>Column::<Field>(<Fragment>Column::<Column>)` and its columns follow
/// the field's position in `all()`.
///
/// `query_ops` records which comparisons a column supports in
/// `Column::query_ops`; it is metadata, not query code.
///
/// A field without `pgtype` takes its type and default from the field type's
/// `dbkit::DbType` implementation, generated by `#[derive(DbType)]`. A field
/// that spells out `pgtype` keeps only the `pgdefault` it declares itself;
/// a bare `#[db(pgdefault)]` states that the column has no default.
///
/// `table` or `subquery`, a column type per field and, for a table,
/// `primary_key` are required; a table without a version or audit column omits
/// those role annotations. A subquery is read-only: it takes no roles and no
/// `DbPatch`. `pgtype`
/// is the column type as DDL spells it (`uuid`, `text`, `bigint`,
/// `timestamptz`, `varchar(255)`, `numeric(10,2)`, `text[]`), so it can be
/// checked against the database and later generate `schema.sql`. `pgdefault`
/// is the optional column default in the same notation (`now()`, `0`,
/// `'{}'::jsonb`), which the schema test compares with the database and which
/// marks the column as safe to omit on insert.
#[proc_macro_derive(DbModel, attributes(db))]
pub fn derive_db_model(input: TokenStream) -> TokenStream {
    let input = syn::parse_macro_input!(input as DeriveInput);

    match expand(&input) {
        Ok(tokens) => tokens.into(),
        Err(error) => error.to_compile_error().into(),
    }
}

/// Records the database type of a value type, so a model field of that type
/// needs no `pgtype` or `pgdefault` of its own.
///
/// Accepted on the struct: `#[db(pgtype = "...")]`, required, and
/// `#[db(pgdefault = "...")]`, optional. Both hold DDL the way `pgtype` and
/// `pgdefault` do on a model field. Field annotations are not accepted.
///
/// Generates `impl dbkit::DbType`, whose `PG_TYPE` and `PG_DEFAULT` constants
/// a `#[derive(DbModel)]` model reads for a field that omits `pgtype`. The
/// default is a suggestion, not a column rule: a model field that declares its
/// own `pgtype` does not inherit it, and a bare `#[db(pgdefault)]` clears it.
#[proc_macro_derive(DbType, attributes(db))]
pub fn derive_db_type(input: TokenStream) -> TokenStream {
    let input = syn::parse_macro_input!(input as DeriveInput);

    match expand_type(&input) {
        Ok(tokens) => tokens.into(),
        Err(error) => error.to_compile_error().into(),
    }
}

/// Generates the patch input type of a model, `<Model>Patch`.
///
/// Reads the same `#[db(...)]` annotations as `DbModel`. The primary key is a
/// required field of the patch, taken as it is, and so is the version when the
/// model has one; every other business column becomes a `dbkit::Patch<T>`
/// field, so a missing key leaves the column unchanged and an explicit `null`
/// clears a nullable one. Audit columns (`created_at`, `updated_at`) are not
/// patchable and are omitted. A `#[db(subquery = "...")]` model is read-only
/// and rejected.
///
/// The generated struct is `Serialize + Deserialize + garde::Validate`. A
/// patch field whose payload type can carry rules derives a `#[garde(dive)]`,
/// so `Patch::Set` values are validated while `Patch::Absent` and
/// `Patch::Null` pass.
#[proc_macro_derive(DbPatch, attributes(db))]
pub fn derive_db_patch(input: TokenStream) -> TokenStream {
    let input = syn::parse_macro_input!(input as DeriveInput);

    match derive_patch::expand(&input) {
        Ok(tokens) => tokens.into(),
        Err(error) => error.to_compile_error().into(),
    }
}

/// Generates `impl From<&T> for T` for a one-field tuple struct, so a column
/// handle takes `&value` as well as `value`.
///
/// The conversion clones, so the struct must derive or implement `Clone`; the
/// compiler reports a missing `Clone` at the derive. A struct that is not a
/// one-field tuple is rejected.
#[proc_macro_derive(DbValue)]
pub fn derive_db_value(input: TokenStream) -> TokenStream {
    let input = syn::parse_macro_input!(input as DeriveInput);

    match derive_value::expand(&input) {
        Ok(tokens) => tokens.into(),
        Err(error) => error.to_compile_error().into(),
    }
}

/// Generates the projected-row type of a model, `<Model>Select`.
///
/// Every column becomes a `dbkit::Selected<T>` field, which is `Set` when the
/// query selected the column and `Absent` when it did not, so one type serves
/// every projection of a table and a selected `NULL` stays distinct from a
/// column nobody asked for. The derive also implements `dbkit::Selectable`,
/// which is the bound `Query::query` needs.
///
/// Reads the same `#[db(...)]` annotations as `DbModel`: a `#[db(flatten)]`
/// field nests the fragment's own select type.
#[proc_macro_derive(DbSelect, attributes(db))]
pub fn derive_db_select(input: TokenStream) -> TokenStream {
    let input = syn::parse_macro_input!(input as DeriveInput);

    match derive_select::expand(&input) {
        Ok(tokens) => tokens.into(),
        Err(error) => error.to_compile_error().into(),
    }
}

fn expand(input: &DeriveInput) -> syn::Result<TokenStream2> {
    let annotations = annotations::parse(input)?;
    let name = &input.ident;
    let columns_type = format_ident!("{name}Column");
    let (impl_generics, type_generics, where_clause) = input.generics.split_for_impl();

    // `Vec` because a `const` cannot splice another type's columns; the list is
    // built once, then leaked so the metadata stays a slice of `'static`.
    let push_columns: Vec<TokenStream2> = annotations
        .columns
        .iter()
        .map(|column| match column {
            annotations::Column::Scalar { name, .. } => {
                let variant = derive_columns::variant(name);
                syn::parse_quote! {
                    columns.push(
                        &#columns_type::#variant
                            as &'static dyn ::dbkit::ErasedColumn
                    );
                }
            }
            annotations::Column::Flattened { name, ty } => syn::parse_quote! {
                match <#ty as ::dbkit::Model>::meta() {
                    ::dbkit::Meta::Fragment(fragment) => {
                        columns.extend_from_slice(fragment.columns);
                    }
                    ::dbkit::Meta::Table(meta) => panic!(
                        "`#[db(flatten)]` field `{}` has type `{}`, which is a table; \
                         flattened fields must be `#[db(fragment)]` structs",
                        ::core::stringify!(#name),
                        meta.table,
                    ),
                    ::dbkit::Meta::SubQuery(_) => panic!(
                        "`#[db(flatten)]` field `{}` has type `{}`, which is a subquery; \
                         flattened fields must be `#[db(fragment)]` structs",
                        ::core::stringify!(#name),
                        ::core::stringify!(#ty),
                    ),
                }
            },
        })
        .collect();

    let metadata = match &annotations.shape {
        annotations::Shape::Fragment => quote! {
            static META: ::std::sync::OnceLock<::dbkit::TableFragment> =
                ::std::sync::OnceLock::new();

            ::dbkit::Meta::Fragment(META.get_or_init(|| {
                let mut columns: ::std::vec::Vec<&'static dyn ::dbkit::ErasedColumn> =
                    ::std::vec::Vec::new();
                #(#push_columns)*

                ::dbkit::TableFragment {
                    columns: ::std::boxed::Box::leak(columns.into_boxed_slice()),
                }
            }))
        },
        annotations::Shape::SubQuery(sql) => quote! {
            static META: ::std::sync::OnceLock<::dbkit::SubQuery> =
                ::std::sync::OnceLock::new();

            ::dbkit::Meta::SubQuery(META.get_or_init(|| {
                let mut columns: ::std::vec::Vec<&'static dyn ::dbkit::ErasedColumn> =
                    ::std::vec::Vec::new();
                #(#push_columns)*

                ::dbkit::SubQuery {
                    sql: #sql,
                    columns: ::std::boxed::Box::leak(columns.into_boxed_slice()),
                }
            }))
        },
        annotations::Shape::Table(table) => {
            let primary_key: Vec<String> = annotations
                .primary_key
                .iter()
                .map(ToString::to_string)
                .collect();
            let version = optional(annotations.version.as_ref());
            let created_at = optional(annotations.created_at.as_ref());
            let updated_at = optional(annotations.updated_at.as_ref());

            quote! {
                static META: ::std::sync::OnceLock<::dbkit::TableMeta> =
                    ::std::sync::OnceLock::new();

                ::dbkit::Meta::Table(META.get_or_init(|| {
                    let mut columns: ::std::vec::Vec<&'static dyn ::dbkit::ErasedColumn> =
                        ::std::vec::Vec::new();
                    #(#push_columns)*

                    ::dbkit::TableMeta {
                        table: #table,
                        primary_key: &[#(#primary_key),*],
                        version: #version,
                        created_at: #created_at,
                        updated_at: #updated_at,
                        columns: ::std::boxed::Box::leak(columns.into_boxed_slice()),
                    }
                }))
            }
        }
    };

    let columns = derive_columns::expand(input, &annotations)?;

    Ok(quote! {
        #[automatically_derived]
        impl #impl_generics ::dbkit::Model for #name #type_generics #where_clause {
            fn meta() -> ::dbkit::Meta {
                #metadata
            }
        }

        #columns
    })
}

fn optional<T: ToString>(name: Option<T>) -> Expr {
    match name {
        Some(name) => {
            let name = name.to_string();
            syn::parse_quote!(::core::option::Option::Some(#name))
        }
        None => syn::parse_quote!(::core::option::Option::None),
    }
}

fn expand_type(input: &DeriveInput) -> syn::Result<TokenStream2> {
    let annotations = annotations::parse_type(input)?;
    let name = &input.ident;
    let (impl_generics, type_generics, where_clause) = input.generics.split_for_impl();
    let pg_type = &annotations.pg_type;
    let pg_default = optional(annotations.pg_default.as_deref());

    Ok(syn::parse_quote! {
        #[automatically_derived]
        impl #impl_generics ::dbkit::DbType for #name #type_generics #where_clause {
            const PG_TYPE: &'static str = #pg_type;
            const PG_DEFAULT: ::core::option::Option<&'static str> = #pg_default;
        }
    })
}
