use dbkit::DbModel;
use dbkit::Model;
use dbkit::TableMeta;
use dbkit::schema::Schema;
use dbkit::schema::SchemaSource;
use std::sync::LazyLock;
use uuid::Uuid;

#[derive(DbModel)]
#[db(table = "parent")]
#[db(index(columns = [name]))]
#[expect(
    dead_code,
    reason = "the fields exist only to derive the table metadata"
)]
struct Parent {
    #[db(primary_key, pgtype = "uuid", pgdefault = "uuidv7()")]
    id: Uuid,

    #[db(pgtype = "text")]
    #[db(unique)]
    name: String,
}

#[derive(DbModel)]
#[db(table = "child")]
#[db(pg_trigger(
    name = "child_trigger",
    timing = before,
    events(insert, update),
    body = "begin new.\"amount\" := 1; return new; end;"
))]
#[expect(
    dead_code,
    reason = "the fields exist only to derive the table metadata"
)]
struct Child {
    #[db(primary_key, pgtype = "uuid", pgdefault = "uuidv7()")]
    id: Uuid,

    #[db(pgtype = "uuid")]
    #[db(foreign_key(table = "parent", column = "id", on_delete = cascade))]
    parent_id: Uuid,

    #[db(pgtype = "int8")]
    amount: i64,

    #[db(pgtype = "int8")]
    #[db(pg_virtual = "\"amount\" + 1")]
    total: i64,
}

static PARENT_MODELS: LazyLock<Vec<TableMeta>> =
    LazyLock::new(|| vec![Parent::meta().into_table()]);
static CHILD_MODELS: LazyLock<Vec<TableMeta>> = LazyLock::new(|| vec![Child::meta().into_table()]);

static PARENT: Schema = Schema {
    name: "parent",
    sql: "",
    models: &PARENT_MODELS,
    dependencies: &[],
    source: SchemaSource::Generated,
};

static CHILD: Schema = Schema {
    name: "child",
    sql: "",
    models: &CHILD_MODELS,
    dependencies: &[&PARENT],
    source: SchemaSource::Generated,
};

#[test]
fn generates_columns_keys_indexes_and_foreign_keys() {
    let sql = PARENT.generate().unwrap();

    assert!(sql.contains("create table \"parent\""));
    assert!(sql.contains("\"id\" uuid not null default uuidv7()"));
    assert!(sql.contains("constraint \"parent_pkey\" primary key (\"id\")"));
    assert!(sql.contains("constraint \"parent_name_key\" unique (\"name\")"));
    assert!(sql.contains("create index \"parent_name_idx\" on \"parent\" (\"name\");"));
}

#[test]
fn generates_a_fragment_with_a_cross_table_foreign_key() {
    let sql = CHILD.generate().unwrap();

    assert!(sql.starts_with("-- Generated by dbkit from the \"child\" schema. Requires: parent."));
    assert!(sql.contains("create table \"child\""));
    assert!(!sql.contains("create table \"parent\""));
    assert!(sql.contains("\"total\" int8 generated always as (\"amount\" + 1) virtual not null"));
    assert!(sql.contains(
        "alter table \"child\" add constraint \"child_parent_id_fkey\" foreign key \
         (\"parent_id\") references \"parent\" (\"id\") on delete cascade;"
    ));
    assert!(sql.contains("create function \"child_trigger\"() returns trigger"));
    assert!(sql.contains("execute function \"child_trigger\"();"));
}

#[test]
fn rejects_a_foreign_key_target_outside_the_composition() {
    let problems = dbkit::schema::generate(&CHILD_MODELS, &CHILD_MODELS).unwrap_err();

    assert!(
        problems
            .iter()
            .any(|problem| problem.contains("references table \"parent\"")),
        "{problems:?}"
    );
}

#[test]
fn rejects_a_handwritten_schema() {
    static HANDWRITTEN: Schema = Schema {
        name: "handwritten",
        sql: "",
        models: &PARENT_MODELS,
        dependencies: &[],
        source: SchemaSource::Handwritten,
    };

    let problems = HANDWRITTEN.generate().unwrap_err();

    assert!(problems[0].contains("is hand-written"), "{problems:?}");
}
