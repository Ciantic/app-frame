use serde::Deserialize;
use serde::Serialize;

/// A comparison a column supports, as declared by
/// `#[db(query_ops(...))]`.
///
/// This is metadata only: `dbkit` records which operators a column accepts so
/// that a query layer can validate a request against it. Nothing here builds
/// SQL.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum FilterOperator {
    Eq,
    Neq,
    Gt,
    Gte,
    Lt,
    Lte,
    Like,
    ILike,
    NotLike,
    NotILike,
    In,
    NotIn,
    Any,
    NotAny,
    IsNull,
    IsNotNull,
    Between,
    NotBetween,
}

/// A column of a model table, as declared by the model struct.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ColumnMeta {
    pub name: &'static str,
    pub nullable: bool,
    /// Column type as DDL spells it: `uuid`, `text`, `varchar(255)`, `text[]`.
    pub pg_type: &'static str,
    /// Column default as DDL spells it, or `None` when the column has none.
    pub pg_default: Option<&'static str>,
    /// Operators the column may be queried with, as declared by
    /// `#[db(query_ops(...))]`, in declaration order.
    ///
    /// Empty when the field carries no `query_ops` annotation.
    pub query_ops: &'static [FilterOperator],
}

/// Table-level description generated by `#[derive(DbModel)]`.
///
/// Every model exposes one as [`Model::META`], which is what a crate's
/// `MODELS` list collects and what schema tests compare against the database.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TableMeta {
    pub table: &'static str,
    /// Primary key columns in declaration order; never empty.
    pub primary_key: &'static [&'static str],
    pub version: Option<&'static str>,
    pub created_at: Option<&'static str>,
    pub updated_at: Option<&'static str>,
    /// Every field in declaration order.
    pub columns: &'static [ColumnMeta],
}

/// A row type of one table.
pub trait Model {
    const META: TableMeta;
}
